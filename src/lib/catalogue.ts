const CATEGORY_NAME_MAP = Object.fromEntries(
  CATALOG_CATEGORIES.map((c) => [c.id, c.name]),
) as Record<CatalogCategoryId, string>;

function makeItem(
  displayOrder: number,
  id: string,
  name: string,
  categoryId: CatalogCategoryId,
  subcategory: string,
  description: string,
  keywords: string[],
  options?: { featured?: boolean; badge?: string; confirmationNote?: string },
): CatalogProductItem {
  return {
    id,
    name,
    categoryId,
    category: CATEGORY_NAME_MAP[categoryId],
    subcategory,
    image: productImg(id, `${name} — ${CATEGORY_NAME_MAP[categoryId]}`),
    description,
    keywords: [name, CATEGORY_NAME_MAP[categoryId], subcategory, ...keywords],
    displayOrder,
    ...(options ?? {}),
  };
}

